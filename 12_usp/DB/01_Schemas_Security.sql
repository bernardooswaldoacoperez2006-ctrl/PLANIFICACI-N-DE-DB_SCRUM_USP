USE [DB_SCRUM_PLANNING];
GO
IF SCHEMA_ID(N'SQM_SECURITY') IS NULL EXEC(N'CREATE SCHEMA [SQM_SECURITY]');
IF SCHEMA_ID(N'SQM_CATALOGS') IS NULL EXEC(N'CREATE SCHEMA [SQM_CATALOGS]');
IF SCHEMA_ID(N'SQM_GENERAL') IS NULL EXEC(N'CREATE SCHEMA [SQM_GENERAL]');
GO
/* Cambia esta contraseña antes de ejecutar en un entorno real y guárdala de forma segura. */
IF NOT EXISTS (SELECT 1 FROM sys.symmetric_keys WHERE name = N'##MS_DatabaseMasterKey##')
    CREATE MASTER KEY ENCRYPTION BY PASSWORD = 'CAMBIAR_POR_UNA_CLAVE_MAESTRA_LARGA_Y_UNICA_2026!';
GO
IF NOT EXISTS (SELECT 1 FROM sys.certificates WHERE name = N'CERT_SCRUMPLANNING')
    CREATE CERTIFICATE [CERT_SCRUMPLANNING]
    WITH SUBJECT = 'Certificado para cifrado de contrasenas de SCRUM_PLANNING';
GO
IF NOT EXISTS (SELECT 1 FROM sys.symmetric_keys WHERE name = N'KEY_HASH')
    CREATE SYMMETRIC KEY [KEY_HASH]
    WITH ALGORITHM = AES_256
    ENCRYPTION BY CERTIFICATE [CERT_SCRUMPLANNING];
GO
CREATE OR ALTER FUNCTION [SQM_SECURITY].[Fn_EncryptByKey] (@PlainText VARCHAR(256))
RETURNS VARBINARY(256)
AS
BEGIN
    RETURN EncryptByKey(Key_GUID(N'KEY_HASH'), CONVERT(VARBINARY(256), @PlainText));
END;
GO
